"""Generate PostgreSQL import scripts for completed scraper runs."""

from __future__ import annotations

from decimal import Decimal, InvalidOperation
from pathlib import Path
from typing import Any


def write_import_sql(
    directory: str | Path,
    *,
    run_id: int,
    store_slug: str,
    store_id: int,
    items: list[dict[str, Any]],
) -> Path:
    """Write a transaction that upserts products, images and offers."""
    target_dir = Path(directory)
    target_dir.mkdir(parents=True, exist_ok=True)
    path = target_dir / f"run-{run_id}-{store_slug}.sql"
    lines = [
        f"-- Generated by SOLOServis scraper; run={run_id}, store={store_slug}.",
        "-- Review the category/store IDs and apply only after backing up the database.",
        "BEGIN;",
        "DO $scraper$",
        "DECLARE",
        "    v_category_id INTEGER;",
        "    v_brand_id INTEGER;",
        "    v_product_id INTEGER;",
        "BEGIN",
        f"    IF NOT EXISTS (SELECT 1 FROM store WHERE id = {store_id} AND active) THEN",
        f"        RAISE EXCEPTION 'Active store id % does not exist', {store_id};",
        "    END IF;",
    ]

    for index, item in enumerate(items, start=1):
        product = _object(item, "product", index)
        offer = _object(item, "offer", index)
        category_slug = _required_text(product, "categorySlug", index)
        name = _required_text(product, "name", index)
        price = _numeric(_required_text(offer, "price", index), "price", index)
        list_price = _nullable_numeric(offer.get("listPrice"), "listPrice", index)
        shipping_cost = _numeric(offer.get("shippingCost", "0"), "shippingCost", index)
        currency = _required_text(offer, "currency", index)
        condition = _required_text(offer, "condition", index)
        if condition not in {"new", "used", "refurbished"}:
            raise ValueError(f"item {index}: unsupported offer.condition {condition!r}")

        brand = _nullable_text(product.get("brand"))
        sku = _nullable_text(product.get("sku"))
        model = _nullable_text(product.get("model"))
        description = _nullable_text(product.get("description"))
        image_url = _nullable_text(product.get("imageUrl"))
        product_url = _nullable_text(offer.get("productUrl") or item.get("externalUrl"))

        lines.extend(
            [
                "",
                f"    -- Product {index}: {name}",
                "    SELECT legacy_product_category_id INTO v_category_id",
                "    FROM categories",
                f"    WHERE slug = {_literal(category_slug)}",
                "      AND item_type = 'product' AND active",
                "      AND legacy_product_category_id IS NOT NULL;",
                "    IF v_category_id IS NULL THEN",
                "        RAISE EXCEPTION 'No active legacy product category for slug %', "
                + _literal(category_slug)
                + ";",
                "    END IF;",
            ]
        )
        if brand:
            lines.extend(
                [
                    "    SELECT id INTO v_brand_id FROM brand",
                    f"    WHERE lower(name) = lower({_literal(brand)})",
                    "    ORDER BY id LIMIT 1;",
                    "    IF v_brand_id IS NULL THEN",
                    f"        INSERT INTO brand (name) VALUES ({_literal(brand)})",
                    "        ON CONFLICT (name) DO NOTHING;",
                    "        SELECT id INTO v_brand_id FROM brand",
                    f"        WHERE lower(name) = lower({_literal(brand)})",
                    "        ORDER BY id LIMIT 1;",
                    "    END IF;",
                ]
            )
        else:
            lines.append("    v_brand_id := NULL;")

        lines.extend(
            [
                "    SELECT p.id INTO v_product_id",
                "    FROM product p",
                "    WHERE "
                + (
                    f"(p.sku = {_literal(sku)}) OR "
                    if sku
                    else ""
                )
                + (
                    "(p.brand_id = v_brand_id AND lower(p.model) = lower("
                    f"{_literal(model)})) OR "
                    if brand and model
                    else ""
                )
                + "(p.category_id = v_category_id "
                "AND p.brand_id IS NOT DISTINCT FROM v_brand_id "
                f"AND lower(p.name) = lower({_literal(name)}))",
                "    ORDER BY p.active DESC, p.id",
                "    LIMIT 1;",
                "    IF v_product_id IS NULL THEN",
                "        INSERT INTO product (",
                "            category_id, brand_id, name, model, sku, description",
                "        )",
                "        VALUES (",
                "            v_category_id,",
                "            v_brand_id,",
                f"            {_literal(name)},",
                f"            {_literal(model)},",
                f"            {_literal(sku)},",
                f"            {_literal(description)}",
                "        ) RETURNING id INTO v_product_id;",
                "    END IF;",
            ]
        )
        if image_url:
            lines.extend(
                [
                    "    INSERT INTO product_image (product_id, image_url, alt_text, sort_order)",
                    f"    SELECT v_product_id, {_literal(image_url)}, {_literal(name)}, 0",
                    "    WHERE NOT EXISTS (",
                    "        SELECT 1 FROM product_image",
                    "        WHERE product_id = v_product_id AND image_url = "
                        + _literal(image_url),
                    "    );",
                ]
            )
        lines.extend(
            [
                "    INSERT INTO product_offer (",
                "        product_id, store_id, price, list_price, currency, shipping_cost,",
                "        shipping_free, available, stock, condition, product_url",
                "    ) VALUES (",
                f"        v_product_id, {store_id}, {price}, {list_price}, {_literal(currency)},",
                f"        {shipping_cost}, {_boolean(offer.get('shippingFree', False))},",
                f"        {_boolean(offer.get('available', True))},",
                f"        {_nullable_integer(offer.get('stock'), index)},",
                f"        {_literal(condition)}, {_literal(product_url)}",
                "    )",
                "    ON CONFLICT (",
                "        product_id, store_id,",
                "        (COALESCE(normalize_product_offer_url(product_url), ''))",
                "    ) DO UPDATE SET",
                "        price = EXCLUDED.price,",
                "        list_price = EXCLUDED.list_price,",
                "        currency = EXCLUDED.currency,",
                "        shipping_cost = EXCLUDED.shipping_cost,",
                "        shipping_free = EXCLUDED.shipping_free,",
                "        available = EXCLUDED.available,",
                "        stock = EXCLUDED.stock,",
                "        condition = EXCLUDED.condition,",
                "        product_url = EXCLUDED.product_url,",
                "        last_updated = NOW();",
            ]
        )

    lines.extend(["END;", "$scraper$;", "COMMIT;", ""])
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def _object(item: dict[str, Any], key: str, index: int) -> dict[str, Any]:
    value = item.get(key)
    if not isinstance(value, dict):
        raise ValueError(f"item {index}: {key} must be an object")
    return value


def _required_text(values: dict[str, Any], key: str, index: int) -> str:
    value = values.get(key)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"item {index}: {key} is required")
    return value.strip()


def _nullable_text(value: Any) -> str | None:
    return value.strip() if isinstance(value, str) and value.strip() else None


def _numeric(value: Any, field: str, index: int) -> str:
    try:
        number = Decimal(str(value))
    except (InvalidOperation, ValueError) as exc:
        raise ValueError(f"item {index}: invalid {field} {value!r}") from exc
    if not number.is_finite() or number < 0:
        raise ValueError(f"item {index}: {field} must be a non-negative number")
    return format(number, "f")


def _nullable_numeric(value: Any, field: str, index: int) -> str:
    return "NULL" if value is None else _numeric(value, field, index)


def _nullable_integer(value: Any, index: int) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        raise ValueError(f"item {index}: stock must be a non-negative integer or null")
    return str(value)


def _literal(value: str | None) -> str:
    return "NULL" if value is None else "'" + value.replace("'", "''") + "'"


def _boolean(value: Any) -> str:
    if not isinstance(value, bool):
        raise ValueError(f"expected boolean, got {value!r}")
    return "TRUE" if value else "FALSE"
